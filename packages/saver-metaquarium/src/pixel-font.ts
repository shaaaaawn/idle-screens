/** What a character draws as: its own glyph, its capital, or a `?`. */
function glyphOf(ch: string): readonly string[] {
  return G[ch] ?? G[ch.toUpperCase()] ?? G['?']!;
}

/** Characters the font draws as themselves (lower case counts: it becomes capitals). */
export function drawable(ch: string): boolean {
  return ch in G || ch.toUpperCase() in G;
}

export const FONT_W = 5;
export const FONT_H = 7;

/** A line of text as lit pixels: one 5×7 cell a character, a blank column between. */
export interface PixelText {
  /** Width and height in pixels. */
  w: number;
  h: number;
  /** Row-major, top row first: 1 = lit. */
  bits: Uint8Array;
}

export function rasterText(text: string): PixelText {
  const chars = [...text];
  const w = Math.max(0, chars.length * (FONT_W + 1) - 1), h = FONT_H;
  const bits = new Uint8Array(Math.max(1, w) * h);
  chars.forEach((ch, i) => {
    const g = glyphOf(ch);
    for (let y = 0; y < FONT_H; y++) for (let x = 0; x < FONT_W; x++) {
      if (g[y]![x] === '#') bits[y * w + i * (FONT_W + 1) + x] = 1;
    }
  });
  return { w, h, bits };
}
